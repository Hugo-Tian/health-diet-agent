import { chromium } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'
const root=path.resolve('..'),out=path.join(root,'work','browser')
await fs.mkdir(out,{recursive:true})
const browser=await chromium.launch({headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1000}})
const page=await context.newPage(),failures=[]
page.on('pageerror',e=>failures.push(e.message))
const email=`browser-${Date.now()}@example.com`,password='browser-test-12345'
const base=process.env.APP_TEST_URL||'http://127.0.0.1:8000'
async function noOverflow(page,label){const dimensions=await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));if(dimensions.scroll>dimensions.client)throw new Error(label+' overflow '+JSON.stringify(dimensions))}
async function waitIdle(page){await page.getByRole('status').filter({hasText:'正在处理'}).waitFor({state:'hidden'})}
try {
  await page.goto(base)
  await page.getByRole('button',{name:'还没有账号？注册'}).click()
  await page.getByLabel('邮箱',{exact:true}).fill(email)
  await page.getByLabel('密码',{exact:true}).fill(password)
  await page.getByRole('button',{name:'注册并开始',exact:true}).click()
  await page.getByLabel('我确认已满 18 周岁').check()
  await page.getByLabel('年龄（可选）').fill('25')
  await page.getByRole('button',{name:'下一步',exact:true}).click()
  await page.getByLabel('每日预算（元，可选）').fill('45')
  await page.getByRole('button',{name:'下一步',exact:true}).click()
  await page.getByLabel('确认这个目标').check()
  await page.getByRole('button',{name:'保存档案与目标',exact:true}).click()
  await page.getByRole('button',{name:'生成计划草案',exact:true}).click()
  await page.getByRole('button',{name:'确认应用',exact:true}).click()
  await page.locator('.meal-card').nth(1).getByRole('button',{name:'记录实际吃的'}).click()
  await page.getByRole('button',{name:'保存实际记录',exact:true}).click()
  await page.getByRole('button',{name:'查看今日反馈'}).click()
  await page.getByRole('heading',{name:'把已经吃的记清楚，再决定下一餐。'}).waitFor()
  await page.locator('.meal-card').nth(2).getByRole('button',{name:'换一种'}).click()
  await page.getByRole('button',{name:'确认应用',exact:true}).click()
  await waitIdle(page)
  await noOverflow(page,'1440 today')
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:path.join(out,'desktop-1440.png'),fullPage:true})
  const me=await (await context.request.get(base+'/api/v1/auth/me')).json()
  const profile=await (await context.request.get(base+'/api/v1/profile')).json()
  const selectedDay=profile.today
  const desktopSummary=await (await context.request.get(base+'/api/v1/daily-summary?date='+selectedDay)).json()
  if(desktopSummary.confirmed_count!==1||desktopSummary.planned.version!==2)throw new Error('Desktop loop did not persist')
  await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'助手',exact:true}).click()
  await page.getByRole('button',{name:'看看今天的记录',exact:true}).click()
  if(await page.locator('.chat-composer input[type=checkbox]').count())await page.locator('.chat-composer input[type=checkbox]').check()
  await page.getByRole('button',{name:'发送',exact:true}).click()
  await page.locator('.assistant-bubble').first().waitFor()
  await noOverflow(page,'1440 assistant')
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  const mp=await mobile.newPage();mp.on('pageerror',e=>failures.push(e.message))
  await mp.goto(base)
  await mp.getByLabel('邮箱',{exact:true}).fill(email)
  await mp.getByLabel('密码',{exact:true}).fill(password)
  await mp.getByRole('button',{name:'登录',exact:true}).click()
  await mp.getByText('生效 v2',{exact:true}).waitFor()
  await noOverflow(mp,'390 today')
  await mp.evaluate(()=>window.scrollTo(0,0))
  await mp.screenshot({path:path.join(out,'mobile-390.png'),fullPage:true})
  const nav=mp.getByRole('navigation',{name:'手机导航'})
  await nav.getByRole('button',{name:'记录',exact:true}).click()
  await mp.getByRole('button',{name:'编辑 / 确认',exact:true}).click()
  await mp.getByLabel('备注',{exact:true}).fill('手机修改，电脑同步')
  await noOverflow(mp,'390 record modal')
  await mp.screenshot({path:path.join(out,'mobile-record.png'),fullPage:true})
  await mp.getByRole('button',{name:'保存实际记录',exact:true}).click()
  await waitIdle(mp)
  await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'记录',exact:true}).click()
  await page.getByRole('button',{name:'刷新服务器数据',exact:true}).click()
  await page.getByText('手机修改，电脑同步',{exact:true}).waitFor()
  for(const label of ['助手','趋势','我的']){
    await nav.getByRole('button',{name:label,exact:true}).click()
    await noOverflow(mp,'390 '+label)
  }
  await mobile.close()
  if(failures.length)throw new Error('Browser JS errors: '+failures.join('; '))
  const exportResponse=await context.request.get(base+'/api/v1/account/export')
  if(exportResponse.status()!==200)throw new Error('Export failed')
  const latest=await (await context.request.get(base+'/api/v1/profile')).json()
  const deleted=await context.request.delete(base+`/api/v1/account?revision=${latest.revision}&confirm=DELETE`,{headers:{'X-CSRF-Token':me.csrf}})
  if(deleted.status()!==200)throw new Error('Test account cleanup failed')
  await fs.writeFile(path.join(out,'result.json'),JSON.stringify({passed:true,desktop:1440,mobile:390,checks:['registration','profile wizard','proposal confirmation','lunch log','feedback','dinner adjustment','LangChain assistant','cross-browser sharing','mobile edit','export','account deletion','no horizontal overflow','no JavaScript exceptions']},null,2))
  console.log('PASS: desktop + mobile full workflow, cross-browser sharing, no overflow, account removed.')
} catch(e){await page.screenshot({path:path.join(out,'failure.png'),fullPage:true});throw e}
finally{await browser.close()}
