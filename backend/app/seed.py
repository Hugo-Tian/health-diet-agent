def seed_demo(db):
    if db.scalar(select(Food.id).limit(1)): return
    for row in ROWS:
        name, group, state, kcal, protein, carbs, fat, allergens, tags, grams, unit = row
        food = Food(name=name, group=group, state=state, nutrients=dict(kcal=kcal, protein=protein, carbs=carbs, fat=fat), allergens=allergens, tags=tags, source='演示估算：开发样例，非权威数据库', version='demo-1')
        db.add(food); db.flush()
        db.add(Portion(food_id=food.id, unit=unit, grams=grams))
    db.commit()

